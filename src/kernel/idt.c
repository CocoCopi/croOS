void isr_install_handler(int n, isr_handler_t handler) {
    if (n >= 0 && n < IDT_ENTRIES) handlers[n] = handler;
}
void isr_uninstall_handler(int n) {
    if (n >= 0 && n < IDT_ENTRIES) handlers[n] = 0;
}

/* Called from ISR stubs */
void isr_handler(regs_t *r) {
    if (handlers[r->int_no]) {
        handlers[r->int_no](r);
    } else {
        vga_set_color(0x0C, 0x00);
        vga_puts("\n[ISR] Unhandled exception #");
        vga_put_dec(r->int_no);
        if (r->int_no < 22) {
            vga_puts(" : ");
            vga_puts(exception_msgs[r->int_no]);
        }
        vga_puts("\n[ISR] EIP=");
        vga_put_hex(r->eip);
        vga_puts(" CS=");
        vga_put_hex(r->cs);
        vga_puts(" EFLAGS=");
        vga_put_hex(r->eflags);
        vga_puts("\n[System HALTED]");
        cli(); hlt();
    }
}

/* Called from IRQ stubs */
void irq_handler(regs_t *r) {
    /* Send EOI */
    if (r->int_no >= 40) outb(0xA0, 0x20);
    outb(0x20, 0x20);

    if (handlers[r->int_no]) handlers[r->int_no](r);
}
